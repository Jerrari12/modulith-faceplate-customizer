/* Builds icons/phosphor.svg, an SVG sprite of the Phosphor icons the customizer uses, the same way the MODULITH
 * planner builds its own (modulith-planner tools/make-icons.mjs): Regular for idle, Fill for active, each symbol
 * `ph-<name>` or `ph-<name>-fill`, used as <svg class="ph"><use href="icons/phosphor.svg#ph-cube"/></svg>.
 * The sprite is committed, so the page needs no build step.
 *
 * Usage: node tools/make-icons.mjs [path to node_modules/@phosphor-icons/core/assets]
 * (defaults to ./node_modules/@phosphor-icons/core/assets). Phosphor is MIT licensed.
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = process.argv[2] || join(root, 'node_modules', '@phosphor-icons', 'core', 'assets');

const ICONS = {
  // top bar and tabs
  'pencil-simple': ['regular', 'fill'], 'squares-four': ['regular', 'fill'], 'download-simple': ['regular'],
  'folder-simple': ['regular'], 'caret-down': ['regular'], 'caret-up': ['regular'], 'caret-left': ['regular'], 'caret-right': ['regular'],
  'sun': ['regular'], 'moon': ['regular', 'fill'],
  // element kinds
  'dots-nine': ['regular'], 'shapes': ['regular'], 'text-t': ['regular'], 'image': ['regular'], 'mountains': ['regular'], 'align-top': ['regular'], 'hand-grabbing': ['regular'], 'bezier-curve': ['regular'], 'cube-transparent': ['regular'],
  // library + inspector
  'plus': ['regular'], 'minus': ['regular'], 'x': ['regular'], 'copy': ['regular'], 'trash': ['regular'],
  'eye': ['regular'], 'eye-slash': ['regular'], 'arrow-up': ['regular'], 'arrow-down': ['regular'],
  'warning': ['regular', 'fill'], 'check': ['regular'], 'info': ['regular'], 'x-circle': ['regular', 'fill'],
  'upload-simple': ['regular'], 'floppy-disk': ['regular'], 'sliders-horizontal': ['regular'], 'stack': ['regular'],
  // toolbar + dock
  'cube': ['regular'], 'grid-four': ['regular', 'fill'], 'ruler': ['regular'], 'corners-out': ['regular'],
  'arrow-line-down': ['regular'], 'arrow-line-up': ['regular'], 'arrow-right': ['regular'],
  'arrow-counter-clockwise': ['regular'], 'arrow-clockwise': ['regular'], 'gauge': ['regular'],
  'flip-horizontal': ['regular', 'fill'], 'shuffle': ['regular'], 'arrow-square-out': ['regular'], 'magnifying-glass': ['regular'],
  'cylinder': ['regular'], 'drop': ['regular'], 'circle': ['regular'], 'target': ['regular'],
};

/* the planner's own drawing of a 3D printer (Phosphor's printer is a paper printer) */
const CUSTOM = ['printer-3d'];

const body = (svg) => svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();

async function main() {
  const symbols = [];
  for (const [name, weights] of Object.entries(ICONS)) {
    for (const w of weights) {
      const file = join(SRC, w, w === 'regular' ? `${name}.svg` : `${name}-${w}.svg`);
      const svg = await readFile(file, 'utf8');
      const id = w === 'regular' ? `ph-${name}` : `ph-${name}-${w}`;
      symbols.push(`<symbol id="${id}" viewBox="0 0 256 256">${body(svg)}</symbol>`);
    }
  }
  for (const name of CUSTOM) {
    const svg = await readFile(join(root, 'icons', 'custom', `${name}.svg`), 'utf8');
    symbols.push(`<symbol id="ph-${name}" viewBox="0 0 256 256">${body(svg)}</symbol>`);
  }
  const out = `<svg xmlns="http://www.w3.org/2000/svg" style="display:none"><!-- generated by tools/make-icons.mjs from @phosphor-icons/core (MIT) and icons/custom/; do not edit -->\n${symbols.join('\n')}\n</svg>\n`;
  await mkdir(join(root, 'icons'), { recursive: true });
  await writeFile(join(root, 'icons', 'phosphor.svg'), out);
  console.log(`${symbols.length} symbols -> icons/phosphor.svg (${(out.length / 1024).toFixed(1)} KB)`);
}

main().catch(e => { console.error(e); process.exit(1); });
